"""F-02 (helper-bytes review, finding 381; native fix in increment18, finding 403): native watch proof.

The authority admits an ADVANCE'd fresh-generation boundary only when the request's ticket field
carries HMAC-SHA256(watch key, "MLWT" || st_dev || st_ino) of the boundary descriptor sent with it.
The watch key is generated by the supervisor and handed only to the authority at birth; this
direct-launch harness plays the supervisor and supplies its own key. Controls: the correct token
advances; a missing token (bytes zeroed below the Python protocol layer), the token of a different
real boundary, and a forged token are rejected by the authority with no generation admitted and no
workload instruction for the new generation. Expectations are hand-authored here before the run.
"""
