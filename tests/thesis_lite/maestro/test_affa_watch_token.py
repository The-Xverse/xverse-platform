SOURCE_SHA256 = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
EXPECTED = {"correct": K.ADVANCED, "missing": K.REJECTED, "foreign": K.REJECTED, "forged": K.REJECTED}


def raw_exchange(h, frame, fds, ticket):
    """Send one AF17 frame with the ticket bytes set below the Python protocol layer."""
    h.sequence += 1
    frame = replace(frame, sequence=h.sequence, deadline_ns=h.end(), epoch=h.epoch)
    data = bytearray(frame.encode())
    data[224:256] = ticket
    h.channel.sendmsg([bytes(data)], [(socket.SOL_SOCKET, socket.SCM_RIGHTS, array.array("i", fds))])
    raw, _, flags, _ = h.channel.recvmsg(321, socket.CMSG_SPACE(16) + socket.CMSG_SPACE(12))
    assert not flags & (socket.MSG_TRUNC | socket.MSG_CTRUNC)
    reply = AuthorityFrame.decode(raw)
    h.epoch = reply.epoch  # a rejection closes the authority and advances its epoch
    if reply.kind in (K.CANCELLED, K.REJECTED):
        h.closed = True
    return reply


@pytest.mark.parametrize("case", sorted(EXPECTED))
def test_advance_requires_the_supervisor_watch_token(authority, case):
    h, work = authority
    h.stage(0)
    h.arm(0)
    assert h.release(0).kind is K.RELEASED
    wait_marker(work / "u0.marker")
    h.stop_retire(0)
    assert h.manager.force_cleanup(h.units[0]["descriptor"]).boundary_released
    desc = BoundaryDescriptor("run", "u0", 2, "next-watch-" + case, 0)
    h.manager.create_frozen(desc)
    fd = h.manager._entries[desc.key].fd
    u = h.units[0]
    u.update(generation=2, operation=b"w" * 16, intent=digest(b"watch-intent-" + case.encode()),
             mirror=digest(b"watch-mirror-" + case.encode()), boundary=digest(b"watch-boundary-" + case.encode()))
    u.pop("handle")
    u.pop("ticket")
    frame = h.frame(K.ADVANCE, 0)
    ticket = {"correct": h.watch_token(fd), "missing": bytes(32),
              "foreign": h.watch_token(h.units[1]["cg"]), "forged": os.urandom(32)}[case]
    epoch_before = h.epoch
    reply = raw_exchange(h, frame, (fd,), ticket)
    members = list(h.manager.residual_membership(desc))
    observations = dict(case=case, reply_kind=reply.kind.name, reply_reason=reply.reason, epoch_before=epoch_before,
                        reply_epoch=reply.epoch, new_boundary_members=members)
    if reply.kind is K.ADVANCED:
        u["descriptor"], u["cg"] = desc, fd
        h.stage(0)
        h.arm(0)
        assert h.release(0).kind is K.RELEASED
        wait_marker(work / "u0.marker", 2)
        observations["new_generation_released"] = True
        h.cancel()
        h.stop_retire(0)
    else:
        # Closed after the rejection: the new generation can never be staged.
        stage = h.rpc(h.frame(K.STAGE, 0))
        observations.update(late_stage=stage.kind.name, marker=(work / "u0.marker").read_bytes().decode())
    output = os.environ.get("MAESTRO_BOUNDARY_RECEIPTS")
    if output:
        target = Path(output)
        target.mkdir(parents=True, exist_ok=True)
        (target / ("affa-watch-token-" + case + ".json")).write_text(json.dumps(dict(
            observations=observations, expected=EXPECTED[case].name, source_sha256=SOURCE_SHA256,
            helper_finding="F-02", accepted=False), indent=2))
    assert reply.kind is EXPECTED[case], observations
    if case != "correct":
        assert reply.reason == 4 and members == [] and observations["late_stage"] == "REJECTED"
        assert observations["marker"] == "EXEC\n", "a workload instruction reached the unadmitted generation"
    else:
        assert reply.epoch == epoch_before + 1


SCOPE = bytes(range(32))


def test_only_a_v2_watch_reply_may_carry_a_token_without_a_child():
    """F02R-02 (finding 405): the packet rule for the token-carrying WATCH reply (kind 20)."""
    reply = BootstrapPacket(20, 3, 123, SCOPE, slot=1, token=b"t" * 32, version=2)
    assert BootstrapPacket.decode(reply.encode(), version=2) == reply
    with pytest.raises(ValueError, match="WATCH"):
        BootstrapPacket(20, 3, 123, SCOPE, slot=1, version=2)  # a WATCH reply must carry its token
    with pytest.raises(ValueError, match="CHILD"):
        # The request carries none; the general token-without-child rule rejects it before the WATCH rule.
        BootstrapPacket(4, 3, 123, SCOPE, slot=1, token=b"t" * 32, version=2)
    with pytest.raises(ValueError, match="CHILD"):
        BootstrapPacket(19, 3, 123, SCOPE, token=b"t" * 32, version=2)  # no other reply without a child
    with pytest.raises(ValueError, match="WIRE-HEADER"):
        BootstrapPacket(20, 3, 123, SCOPE, slot=1, token=b"t" * 32, version=1)  # v1 has no WATCH
    with pytest.raises(ValueError, match="WATCH"):
        BootstrapPacket(20, 3, 123, SCOPE, slot=1, pid=5, token=b"t" * 32, version=2)  # a WATCH reply names no child


def test_client_refuses_an_advance_without_the_retained_watch_token(run_stack, monkeypatch):
    """F02R-03 (finding 405): the client checks the supervisor token before anything is sent."""
    client = connect(run_stack, monkeypatch)
    session, manager, h, _, _, _, _ = run_stack
    scope = BoundaryDescriptor("run", "u0", 2, "watch-token-client", 0)
    manager.create_frozen(scope)
    session.watch(scope, deadline(2))
    fd = manager._entry(scope).fd
    retained = client.watch_token(fd)
    assert retained != bytes(32)
    frame = replace(h.frame(K.INTENT, 0), kind=K.ADVANCE, generation=2, sequence=client.sequence + 1,
                    deadline_ns=h.end(), ticket=bytes(a ^ 1 for a in retained))
    before = client.sequence
    with pytest.raises(ValueError, match="WATCH-TOKEN"):
        client._exchange(frame, fds=(fd,))
    assert client.sequence == before and not client._revoked
